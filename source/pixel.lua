local glyphs={}
local floor=math.floor
function F.init()
  for c,rows in pairs(raw) do
    local data=love.image.newImageData(5,5)
    for y=1,5 do for x=1,5 do
      local on=rows[y]:sub(x,x)=='1'
      data:setPixel(x-1,y-1,1,1,1,on and 1 or 0)
    end end
    local img=love.graphics.newImage(data)
    img:setFilter('nearest','nearest')
    glyphs[c]=img
  end
end
function F.width(str,scale) return #tostring(str)*6*(scale or 2) end
function F.draw(str,x,y,scale,r,g,b,a,align)
  str=tostring(str):upper();scale=scale or 2
  local width=F.width(str,scale)
  if align=='center' then x=x-width/2 elseif align=='right' then x=x-width end
  love.graphics.setColor(r or 1,g or 1,b or 1,a or 1)
  for i=1,#str do local im=glyphs[str:sub(i,i)] or glyphs['?']
    love.graphics.draw(im,floor(x+(i-1)*6*scale),floor(y),0,scale,scale)
  end
end
function F.line(str,x,y,scale) F.draw(str,x,y,scale,.75,.86,.93) end
return F
